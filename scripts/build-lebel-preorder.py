"""Бланк заказа LebeL -> src/data/lebel-preorder.json (товары «под заказ»).

Зачем: LebeL возит под заказ весь свой ассортимент, а на складе лежит малая часть.
Клиент должен видеть и заказывать всё, но понимать, что часть приедет за 2-3 рабочих дня.

Что делает:
  1. читает бланк заказа (Price/lebel-order-form-*.xlsx);
  2. выбрасывает то, что уже есть в priceItems.json (сверка по ЧИСЛОВОЙ части артикула —
     у LebeL к номеру приписан складской хвост «лп»/«лпм»/«еп»/«лк», в 1С номера голые);
  3. раскладывает остальное по категориям сайта и разделам внутри бренда;
  4. пишет журнал, который подхватывает xlsx-to-price-items.py.

Запуск:  .venv/Scripts/python.exe scripts/build-lebel-preorder.py [--apply]
Без --apply только показывает, что получится.
"""
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
FORM = max(ROOT.glob("Price/lebel-order-form-*.xlsx"), key=lambda p: p.name)
PRICE_ITEMS = ROOT / "src/data/priceItems.json"
OUT = ROOT / "src/data/lebel-preorder.json"
# Описания товаров от LebeL, без повторов: {номер: текст}. Отдельным файлом, чтобы
# каталог хранил только номер и не таскал один и тот же текст по 20 раз.
DESC_OUT = ROOT / "src/data/lebel-descriptions.json"

# Срок поставки — ОДНА константа на весь проект. Правится здесь, а не в вёрстке.
LEAD_TIME = "2-3 рабочих дня"


def art_num(value: str) -> str | None:
    """Числовая часть артикула — общий ключ между бланком LebeL и 1С.

    Составной код («6052/8149») — артефакт ребрендинга: актуальна ПЕРВАЯ часть,
    вторая устаревшая. Ведущие нули срезаются: в 1С «0047», у LebeL «47лп».
    """
    head = str(value).strip().split("/")[0]
    m = re.match(r"^\D*(\d+)", head)
    if not m:
        return None
    return m.group(1).lstrip("0") or "0"


# --- Категории сайта (те же 17, что у товаров из 1С) -------------------------
# Порядок важен: правила проверяются сверху вниз, первое совпавшее выигрывает.
# Красители стоят ПЕРЕД укладкой, иначе «Краска ... Cream» уедет в кремы.
CATEGORY_RULES: list[tuple[str, str]] = [
    # --- окислители и осветление: СТРОГО ВЫШЕ красителей ---
    # «Оксидант edol OXY 6%» и «Оксидант LUVIONA OXY PX» содержат имя линейки красителя,
    # а лайтнеры Materia LT/LTEX вообще названы «Краска для волос». Стой это правило ниже,
    # все восемь уехали бы в красители (поймано на реальных данных 21.09.2026).
    (r"оксидант|окислит|\box\s*%|\boxy\b|лайтнер|осветл|обесцвеч|\blt(ex)?\b", "Окислители и осветляющие средства"),
    # --- красители ---
    # Лайфер = Материя μ (сказано пользователем 21.09.2026), полуперманентный -> безаммиачный.
    (r"лайфер|материя\s*[μmu]\b|полуперманент", "Безаммиачные красители"),
    (r"\bqon\b|тонир|демиперманент|оттеночн", "Безаммиачные красители"),
    # ТОЛЬКО слова, означающие сам краситель. Имена линеек (edol, LUVIONA, Materia)
    # здесь стоять НЕ должны: у линейки бывают шампуни и пены, и они уезжали в
    # красители — «Комплект post-bleach шампунь edol BL» и «Пена-уход LUVIONA SCALP»
    # (поймано 21.09.2026). Имя линейки решает раздел, а не категорию.
    (r"красочн|\bкраска\b|\bкраситель", "Аммиачные красители"),
    # --- химия: СТРОГО ВЫШЕ правила «лосьон» ---
    # «Лосьон для химической завивки Шаг1» — это химия, а не уход. Стой правило ниже,
    # три таких лосьона уезжали в «Несмываемый уход» (поймано на прогоне 21.09.2026).
    (r"выпрямлен|\brufor\b|sensor\s*touch|\bplia\b|завивк|перманент.*волн", "Химия волос"),
    # --- подготовка кожи и волос к процедуре ---
    # Решение пользователя 21.09.2026: энзимная пудра — ТЕХНИЧЕСКОЕ средство, а не шампунь:
    # она глубоко очищает и готовит кожу и волосы к процедуре, а не моет голову.
    # Правило стоит выше «шампунь», иначе слово «очищение» увело бы её в мытьё.
    (r"энзимн|глубок\w* очищени|подготов\w* (кожу|волос)", "Технические средства"),
    # Лосьоны LebeL (PROEDIT HAIRSKIN WATERING, CELCERT MELINE WATER) — несмываемый уход;
    # подтверждено пользователем 21.09.2026. У других брендов лосьоны означают другое
    # (химзавивка у SCHWARZKOPF, термозащита у LONDA), но их размечает 1С, не этот скрипт.
    (r"\bлосьон\b", "Несмываемый уход"),
    # --- уход, по типу средства ---
    # Шампунь-корректор цвета — тонирующее средство, а не мытьё. Выше правила «шампунь».
    (r"шампунь-корректор|корректор цвета", "Безаммиачные красители"),
    (r"шампунь|\bshampoo\b", "Шампуни"),
    (r"кондиционер|бальзам-ополаск|\bбальзам\b", "Кондиционеры"),
    (r"\bмаска\b|аромамаска|маска\s+для", "Маски"),
    (r"термозащит", "Термозащита"),
    # Эссенции LEBEL в текущем прайсе размечены как «Несмываемый уход» (Forti, Moist,
    # Sleek, IAU Mother Essence) — идём за существующей разметкой, а не за своей логикой.
    (r"эссенци", "Несмываемый уход"),
    # «Крем-сыворотка CELCERT FORCEN CREAM» — несмываемый уход, а не ампула
    # (решение пользователя 21.09.2026). Стоит ВЫШЕ общего правила «сыворотк».
    (r"крем-сыворотк|сыворотка-крем", "Несмываемый уход"),
    (r"сыворотк|ампул|концентрат|\bдетокс\b", "Ампулы/концентраты"),
    # --- укладка ---
    (r"\bлак\b|лак\s+для\s+волос", "Лаки"),
    # «Пена-уход для кожи головы» — уход, а не укладка. Выше общего правила про пену.
    (r"пена-уход|пена.*для кожи головы", "Несмываемый уход"),
    (r"\bпена\b|\bмусс\b", "Пенки"),
    (r"\bспрей\b|спрей-", "Спреи"),
    (r"\bвоск\b|\bгель\b|крем.*уклад|\btrie\b|стайлинг|\btheo\b", "Крема и гели для укладки"),
    # --- несмываемый уход: ловит остатки ухода ---
    (r"масло|молочко|крем-уход|крем\b|аромакрем|несмываем|флюид|эмульси", "Несмываемый уход"),
    # --- расходники и техника ---
    (r"корпус|дозатор|насадк|распылит|носик|помп", "Расходные материалы"),
    (r"порошок|жидкост|освежител|средство\s+для|очистител", "Технические средства"),
]


# Линейки без аммиака. Определяются по ГРУППЕ: сами товары названы просто
# «Краска для волос ...», и полуперманентность видна только в заголовке группы
# («LebeL Лайфер - полуперманентный краситель»). Лайфер = Материя µ — сказано
# пользователем 21.09.2026.
DEMI_PATTERN = (r"лайфер|материя\s*[μµmu]\b|полуперманент|\bqon\b"
                r"|тонир|демиперманент|оттеночн|шампунь-корректор")


def categorize(name: str, group: str) -> str | None:
    """Две ступени, и порядок между ними — суть всей разметки.

    1) ТИП средства — по НАЗВАНИЮ товара. Группа у LebeL рекламная и длинная
       («Materia NEW-перманентный краситель для стойкого окрашивания»), а внутри неё
       лежит не только краситель: слово «краситель» из заголовка приписало бы
       категорию красителя каждому шампуню и оксиданту этой линейки.
    2) Если это краситель — аммиачный он или нет, решает ЛИНЕЙКА, то есть ГРУППА.
       Товары Лайфера названы просто «Краска для волос…», и без группы они все
       уезжали в аммиачные (59 штук, поймано 21.09.2026).
    """
    category = None
    for hay in (name.lower(), f"{name} {group}".lower()):
        for pattern, cat in CATEGORY_RULES:
            if re.search(pattern, hay):
                category = cat
                break
        if category:
            break
    if category is None:
        return None
    if category in ("Аммиачные красители", "Безаммиачные красители"):
        both = f"{name} {group}".lower()
        return "Безаммиачные красители" if re.search(DEMI_PATTERN, both) else "Аммиачные красители"
    return category


# --- Разделы внутри бренда (как в Каталог.xlsx: «бренд -> раздел») -----------
# Группы бланка длинные и рекламные («Materia NEW-перманентный краситель для...»),
# на сайте нужен короткий человеческий раздел.
SECTION_RULES: list[tuple[str, str]] = [
    (r"^materia\s*g", "Аммиачный краситель >50% седины - Материя G"),
    (r"^materia", "Аммиачный краситель - Материя"),
    (r"лайфер", "Безаммиачный краситель - Материя µ"),
    (r"^edol\s*qon", "Безаммиачный краситель - edol qon"),
    (r"^edol", "Аммиачный краситель - edol"),
    (r"luviona", "Аммиачный краситель - LUVIONA"),
    (r"mix-ton|микстон", "Аммиачный краситель - микстоны"),
    # «MAKE-UP LINE» у LebeL — не декоративная косметика, а яркие оттенки Materia
    # (Materia/ MBE, MR, MO...). Идут в тот же раздел, что и остальная Материя.
    (r"make-up", "Аммиачный краситель - Материя"),
    (r"шампунь-корректор", "Безаммиачный краситель - шампунь-корректор"),
]
# Здесь ТОЛЬКО красители. Линейки ухода и укладки (Viege, Cool Orange, TRIE, Proedit,
# Infinity Aurum) намеренно убраны 21.09.2026: в прайсе они не выносятся в отдельные
# разделы, а группируются по типу средства — см. section_for().


# Категория -> раздел каталога. Имена СКОПИРОВАНЫ из priceItems.json как есть.
# Расхождение хотя бы в одном символе создаёт в каталоге раздел-двойник: на этом
# обожглись 21.09.2026 — «µ» (микро) против «μ» (греческая мю) выглядят одинаково.
CATEGORY_TO_SECTION: dict[str, str] = {
    "Шампуни": "Шампуни для волос",
    "Маски": "Маски для волос",
    "Кондиционеры": "Бальзамы и кондиционеры для волос",
    "Несмываемый уход": "Несмываемый уход",
    "Ампулы/концентраты": "Технические средства",
    "Технические средства": "Технические средства",
    "Расходные материалы": "Расходные материалы",
    "Крема и гели для укладки": "Средства для укладки волос",
    "Спреи": "Средства для укладки волос",
    "Пенки": "Средства для укладки волос",
    "Лаки": "Средства для укладки волос",
    "Термозащита": "Средства для укладки волос",
    "Химия волос": "Химические и перманентные средства для волос",
    "Окислители и осветляющие средства": "Оксиданты и осветляющие средства",
}


COLORANT_CATEGORIES = {"Аммиачные красители", "Безаммиачные красители"}


def section_for(group: str, category: str | None) -> str:
    """Раздел каталога по правилу самого прайса (указание пользователя 21.09.2026:
    «возьми за основу, как папки идут в прайсе»).

    Линейка выносится в раздел ТОЛЬКО у красителей — «Аммиачный краситель - Материя»,
    «Безаммиачный краситель - edol qon». Всё остальное группируется по ТИПУ средства
    («Шампуни для волос», «Несмываемый уход»), без линеек. Именно так устроены все 12
    разделов LEBEL, которые уже есть на сайте.

    Побочная польза, ради которой проверка категории стоит ПЕРВОЙ: оксиданты edol и
    LUVIONA больше не уезжают в раздел своего красителя — они не краситель, значит
    идут в «Оксиданты и осветляющие средства» (замечание пользователя 21.09.2026).
    """
    if category not in COLORANT_CATEGORIES:
        return CATEGORY_TO_SECTION.get(category or "", "Прочее")
    g = group.lower()
    for pattern, section in SECTION_RULES:
        if re.search(pattern, g):
            return section
    return CATEGORY_TO_SECTION.get(category or "", "Прочее")


def read_form() -> list[dict]:
    wb = openpyxl.load_workbook(FORM, read_only=True, data_only=True)
    ws = wb[wb.sheetnames[0]]
    rows = list(ws.iter_rows(min_row=1, values_only=True))
    wb.close()

    items: list[dict] = []
    group = ""
    last_name = ""           # товар в нескольких фасовках: имя стоит только в первой строке
    for row in rows[2:]:
        cell = lambda i: (str(row[i]).strip() if len(row) > i and row[i] is not None else "")
        name, volume, article, desc = cell(1), cell(2), cell(3), cell(8)
        price = row[5] if len(row) > 5 else None

        is_product = article and isinstance(price, (int, float)) and price
        if not is_product:
            if name and not article:
                group = name.split("\n")[0].strip()
                last_name = ""
            continue

        if name:
            last_name = name
        elif not last_name:
            continue                      # артикул без имени и без предыдущего — пропускаем
        full = last_name if not volume else f"{last_name} {volume}мл".replace("мл мл", "мл")
        if name:
            full = name

        items.append({
            "artRaw": article,
            "art": art_num(article),
            "name": re.sub(r"\s+", " ", full).strip(),
            "volume": volume,
            "price": round(float(price), 2),
            "group": group,
            "desc": re.sub(r"\s+", " ", desc).strip()[:400],
        })
    return items


def main() -> int:
    apply = "--apply" in sys.argv
    raw = read_form()
    print(f"Бланк: {FORM.name}")
    print(f"Строк-товаров в бланке: {len(raw)}")

    site = json.loads(PRICE_ITEMS.read_text(encoding="utf-8"))
    site = site if isinstance(site, list) else site.get("items", site)
    # ВАЖНО: берём только настоящие складские позиции (из 1С), а НЕ те, что этот же
    # скрипт добавил в прошлый раз. priceItems.json содержит и то и другое, и без
    # фильтра по preorder получается круг: скрипт видит свой прошлый результат, решает,
    # что добавлять нечего, и записывает пустой файл — данные исчезают молча.
    # Поймано 21.09.2026 на втором прогоне после слияния.
    in_stock = {art_num(i["name"].split()[-1]) for i in site
                if "LEBEL" in str(i.get("brand", "")).upper() and not i.get("preorder")}
    in_stock.discard(None)

    seen: set[str] = set()
    out: list[dict] = []
    skipped_dup = skipped_stock = 0
    for it in raw:
        if not it["art"]:
            continue
        if it["art"] in in_stock:
            skipped_stock += 1
            continue
        if it["art"] in seen:
            skipped_dup += 1
            continue
        seen.add(it["art"])
        it["category"] = categorize(it["name"], it["group"])
        it["section"] = section_for(it["group"], it["category"])
        it["preorder"] = True
        it["leadTime"] = LEAD_TIME
        out.append(it)

    # Страховка от того же круга с другой стороны: если бланк разобрался, а на выходе
    # пусто — это не «нечего добавлять», а сломанная сверка. Лучше упасть, чем тихо
    # затереть журнал нулями (см. комментарий про preorder выше).
    if raw and not out:
        print("СТОП: бланк разобран, но под заказ не осталось ни одной позиции.\n"
              "      Похоже, сверка со складом захватила собственный прошлый результат.\n"
              "      Файлы НЕ перезаписаны.")
        return 1

    print(f"Уже на складе (есть в priceItems) — пропущено: {skipped_stock}")
    print(f"Дубли артикула в бланке — пропущено: {skipped_dup}")
    print(f"ПОД ЗАКАЗ: {len(out)}")

    no_cat = [i for i in out if not i["category"]]
    print(f"\nБез категории: {len(no_cat)}")
    for i in no_cat[:25]:
        print(f"   {i['artRaw']:>9}  {i['name'][:70]}")
    if len(no_cat) > 25:
        print(f"   ... и ещё {len(no_cat) - 25}")

    print("\nПо категориям:")
    for cat, n in Counter(i["category"] or "— НЕ РАСПОЗНАНО —" for i in out).most_common():
        print(f"   {n:4}  {cat}")

    print("\nПо разделам:")
    for sec, n in Counter(i["section"] for i in out).most_common():
        print(f"   {n:4}  {sec}")

    # Описания от LebeL — в отдельный файл и БЕЗ повторов. Внутри линейки текст один и
    # тот же на все оттенки: 522 описания сводятся к 261 уникальному, 142 КБ к 63.
    # Товар хранит только номер текста, поэтому каталог не раздувается.
    texts: dict[str, int] = {}
    for it in out:
        d = it.pop("desc", "")
        if not d:
            continue
        if d not in texts:
            texts[d] = len(texts) + 1
        it["descId"] = texts[d]
    descriptions = {str(n): t for t, n in texts.items()}
    print(f"\nОписаний: {sum(1 for i in out if i.get('descId'))} у товаров, "
          f"{len(descriptions)} уникальных текстов")

    if apply:
        OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
        DESC_OUT.write_text(json.dumps(descriptions, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"Записано: {OUT.relative_to(ROOT)} ({len(out)} позиций)")
        print(f"Записано: {DESC_OUT.relative_to(ROOT)} ({len(descriptions)} текстов)")
    else:
        print("\n(предпросмотр; чтобы записать — запусти с --apply)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
