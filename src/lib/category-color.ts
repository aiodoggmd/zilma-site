// Единая функция «тег статьи → цвет» — источник истины для цвета и карточки в ленте
// (ArticleCard.astro), и баннера-шапки на странице самой статьи ([id].astro). Раньше цвет
// задавался вручную полем accent (blue/red) по ощущению бренда — из-за этого две статьи одной
// категории могли быть разного цвета (Igora Royal и Shinefinity — обе «Колористика», но одна
// синяя, другая красная). Установлено 2026-08-29 по просьбе пользователя: цвет = категория,
// единообразно, без ручного выбора. Тот же цвет уже используется на вкладках FilterTabs.astro —
// если добавляется новая категория, обновить её здесь и там.
export type CategoryColor = 'blue' | 'red' | 'gradient';

export function categoryColor(tags: string[]): CategoryColor {
  const primary = tags[0];
  if (primary === 'уход и восстановление') return 'red';
  if (primary === 'база знаний') return 'gradient';
  return 'blue'; // колористика и любой ещё не размеченный случай — по умолчанию синий
}
