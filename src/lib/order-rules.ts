// Правила оформления заказа — в одном месте.
//
// Порог минимального заказа теперь используется не только формой заявки, но и тонкой
// полосой прогресса в шапке каталога/акций и на страницах статей (2026-09-05). Держать
// одно и то же число в трёх файлах — гарантированное расхождение при следующей правке:
// поменяли бы в форме, а полоса продолжила бы считать от старого.
export const MIN_ORDER_TOTAL = 5000;

/** Доля набранного от минимального заказа, 0…1 (больше 1 не бывает — для ширины полосы). */
export function minOrderProgress(total: number): number {
  return Math.max(0, Math.min(1, total / MIN_ORDER_TOTAL));
}
